// Developer Tools are built into the browser and allow you to inspect and debug your code. You can open them by pressing F12 or right-clicking on the page and selecting "Inspect".

// Element tab: It has the HTML structure of the page and allows you to inspect and modify it. It also has a CSS panel where you can see the styles applied

// Console tab: It allows you to log messages, run JavaScript code, and see errors and warnings. You can use console.log() to print messages to the console.

// Network tab: It shows all the network requests made by the page, including API calls, images, and scripts. You can see the status, response time, and data returned by each request.

// Lighthouse tab: It is a tool that analyzes the performance, accessibility, and best practices of your web page. It provides a report with suggestions for improvement.